# 生成 DeepSeek 鲸鱼像素图标：20x20 RGB，背景 #141A28，鲸鱼 #4D6BFE
from PIL import Image

BG = (20, 26, 40)
BLUE = (77, 107, 254)      # DeepSeek 品牌蓝
BLUE_HI = (122, 148, 255)  # 背部高光
EYE = (232, 236, 245)

GRID = [
    "....................",
    "....................",
    "....................",
    "..#.................",
    "..#.#...............",
    "...#................",
    "...##...............",
    "..#####.........##..",
    ".#######........###.",
    ".#########......###.",
    "###########....###..",
    "############..###...",
    "#################...",
    "##################..",
    ".################...",
    "..##############....",
    "....##########......",
    ".....#######........",
    "....................",
    "....................",
]

im = Image.new("RGB", (20, 20), BG)
px = im.load()
for y, row in enumerate(GRID):
    for x, ch in enumerate(row):
        if ch == "#":
            px[x, y] = BLUE
# 背部高光（顶边一像素浅色，对齐现有图标的明暗层次）
for x, y in [(4, 7), (5, 7), (2, 8), (6, 8), (3, 9), (7, 9), (8, 9)]:
    px[x, y] = BLUE_HI
# 眼睛（亮色小点，头部左侧）
px[4, 11] = EYE
im.save("cubic/package/assets/tm_deepseek.png")
# 放大预览图，便于人工检查
im.resize((200, 200), Image.NEAREST).save("cubic/scripts/tm_deepseek_preview.png")
print("saved", im.size, im.mode)
